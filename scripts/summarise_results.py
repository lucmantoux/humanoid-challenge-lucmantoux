"""Write the 7 Oct narrative from the csv files in results/.

The submission text is RESULTS.md, written from results/v2/. This script reads
the earlier csvs (results/e1.csv, results/e2.csv, results/extraction_report.csv)
and writes results/v1/summary_from_csv.md. It does not replace RESULTS.md.

Usage:
    uv run python scripts/summarise_results.py
"""

from __future__ import annotations

import csv
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
import yaml

import _bootstrap  # noqa: F401

from palm_prior.utils import Timer, load_config, resolve


def _read(path: Path) -> list[dict]:
    with path.open(encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def _pct(n: int, d: int) -> str:
    if d == 0:
        return "0"
    return f"{100.0 * n / d:.1f}%"


def _mean_std(values: list[float]) -> str:
    v = np.asarray(values, float)
    if len(v) == 0:
        return ""
    if len(v) == 1:
        return f"{v[0]:.2f}"
    return f"{v.mean():.2f} ± {v.std():.2f}"


def main(argv: list[str]) -> None:
    cfg = load_config(argv)
    results = resolve(cfg.paths.results)
    report = _read(results / "extraction_report.csv")
    e1 = _read(results / "e1.csv")
    e2 = _read(results / "e2.csv")
    scripted = _read(results / "scripted_check.csv")

    by_type: dict[str, list[dict]] = defaultdict(list)
    for row in report:
        by_type[row["type"]].append(row)

    def n_pass(rows: list[dict]) -> int:
        return sum(int(r["pass"]) for r in rows)

    n_clips = len(report)
    n_ok = n_pass(report)
    start = [float(r["start_err_m"]) for r in report if r["start_err_m"] != ""]
    start_cm = float(np.median(start) * 100.0) if start else float("nan")
    start_max_cm = float(np.max(start) * 100.0) if start else float("nan")

    lines: list[str] = []
    w = lines.append
    w("# 7 October summary")
    w("")
    w("Generated by `scripts/summarise_results.py` from the csv files in `results/`.")
    w("The submission account is `RESULTS.md`, from `results/v2/`. This file is the earlier run.")
    w("")
    w("The question is whether 45 phone clips of a hand moving a lid make a")
    w("simulated Franka Panda any better at knowing where the lid goes. The")
    w("answer is split. Pinning a copied reach to the lid and to the target")
    w("beats one fixed stretch. A predictor trained on the clips does not beat")
    w('the guess "the lid stays still."')
    w("")

    w("## Data QC")
    w("")
    w("Source: `results/extraction_report.csv`. A clip passes when the hand and")
    w("the lid are found on at least 90% of frames, the reprojected pinch is")
    w("within 15 px on the median frame, the opening lid is within 2 cm of the")
    w("photographed pencil mark, and the grasp count matches the clip type")
    w("(one grasp, or zero for a push).")
    w("")
    w("| Type | Clips | Passed |")
    w("|---|---:|---:|")
    for kind in ("success", "F1", "F2", "F3", "F4"):
        rows = by_type.get(kind, [])
        w(f"| {kind} | {len(rows)} | {n_pass(rows)} |")
    w(f"| all | {n_clips} | {n_ok} |")
    w("")
    w(f"Median opening error against the photographed mark: {start_cm:.2f} cm.")
    w(f"Largest: {start_max_cm:.2f} cm. Limit: 2 cm.")
    w("")
    w("The photographed mark is the median opening lid of the clips that start")
    w("on that dot, not the coordinate in `data/raw/dots.yaml`. The tape sits")
    w("toward the chair from the file. Source of the comparison:")
    w("`results/photographed_dots.csv`, written by this script from")
    w("`data/human/clip_*.npz` when those files are present.")
    w("")

    human = resolve(cfg.paths.human_dir)
    dots_path = resolve(cfg.paths.dots)
    photo_rows = []
    if human.exists() and dots_path.exists():
        raw = yaml.safe_load(dots_path.read_text(encoding="utf-8"))
        plan = {int(k): (float(v[0]), float(v[1])) for k, v in raw["dots"].items()}
        seen: dict[int, np.ndarray] = {}
        log = _read(resolve(cfg.paths.recording_log))
        for row in log:
            path = human / f"clip_{int(row['clip']):03d}.npz"
            if not path.exists():
                continue
            data = np.load(path)
            seen[int(row["block_dot"])] = np.asarray(data["block_xy"], float) * 100.0
        out_dots = results / "photographed_dots.csv"
        with out_dots.open("w", encoding="utf-8", newline="") as f:
            writer = csv.writer(f)
            writer.writerow(["dot", "photo_x_cm", "photo_y_cm", "plan_x_cm", "plan_y_cm", "dy_cm"])
            for dot in sorted(plan):
                if dot not in seen:
                    continue
                px, py = float(seen[dot][0]), float(seen[dot][1])
                qx, qy = plan[dot]
                writer.writerow([dot, f"{px:.2f}", f"{py:.2f}", f"{qx:.1f}", f"{qy:.1f}", f"{py - qy:.2f}"])
                photo_rows.append((dot, px, py, qx, qy, py - qy))
    if photo_rows:
        w("| Dot | Photographed (cm) | Plan (cm) | Toward the chair (cm) |")
        w("|---:|---|---|---:|")
        for dot, px, py, qx, qy, dy in photo_rows:
            w(f"| {dot} | {px:.1f}, {py:.1f} | {qx:.0f}, {qy:.0f} | {dy:.1f} |")
        w("")
        w("Source: `results/photographed_dots.csv`.")
        w("")

    hand_frac = [float(r["valid_hand"]) for r in report]
    block_frac = [float(r["valid_block"]) for r in report]
    w(f"Median fraction of frames with a hand: {float(np.median(hand_frac)):.3f}.")
    w(f"Median fraction of frames with a lid: {float(np.median(block_frac)):.3f}.")
    w("Source: `results/extraction_report.csv`, columns `valid_hand` and")
    w("`valid_block`. The red dot in")
    w("`results/extract_demo_001.mp4` is the 3-D pinch drawn back onto the")
    w("photo. The green dot is the pinch measured in the image. They are the")
    w("same point. The check uses the median frame, so a clip can pass while")
    w("the red dot leaves the fingers on other frames. Example previews:")
    w("`results/extract_demo_001.mp4` (success), `results/extract_demo_031.mp4`")
    w("(miss), `results/extract_demo_035.mp4` (drop).")
    w("")

    w("## E1 retargeting")
    w("")
    w("Source: `results/e1.csv`. Seeds 0–49, three goals, one QC-passed success")
    w("clip per episode. Success: lid centre within 3 cm of the target in xy,")
    w("at the right height, gripper open, speed under 1 cm/s. The baseline is")
    w("one similarity fit on clip 1 and the seed-0 plate, reused on every layout.")
    w("Two-anchor refits that similarity so the grasp lands on this lid and the")
    w("release lands on this target.")
    w("")
    w("| Method | plate | pad | box | all | median miss (cm) |")
    w("|---|---:|---:|---:|---:|---:|")
    e1_claims = {}
    for method in ("naive", "two_anchor"):
        part = [r for r in e1 if r["method"] == method]
        cells = []
        for goal in ("plate", "pad", "box"):
            g = [r for r in part if r["goal"] == goal]
            ok = sum(int(r["success"]) for r in g)
            cells.append(f"{ok}/{len(g)}")
        ok = sum(int(r["success"]) for r in part)
        err = np.array([float(r["xy_err_m"]) * 100.0 for r in part])
        med = float(np.median(err)) if len(err) else float("nan")
        w(f"| {method} | {cells[0]} | {cells[1]} | {cells[2]} | {ok}/{len(part)} | {med:.1f} |")
        e1_claims[method] = (ok, len(part), med)
    w("")
    w("Claim: pinning both ends beats a fixed map. The metric is successes out")
    w("of 150. The baseline is `naive`. Variance is the spread of layouts, not")
    w("of training seeds: one deterministic replay per layout. The evidence is")
    w("the table. A miss distance is in `xy_err_m`.")
    w("")
    w("![Top view: the pinned path starts on the lid and ends on the target](results/retarget_top.png)")
    w("")
    w("Side-by-side videos: `results/e1_plate.mp4`, `results/e1_pad.mp4`,")
    w("`results/e1_box.mp4`.")
    w("")
    w("A scripted pick that is told the positions and does not watch the clips")
    w("is the reference for 'the simulator can do the task'. Source:")
    w("`results/scripted_check.csv`.")
    w("")
    w("| Goal | Successes |")
    w("|---|---:|")
    for goal in ("plate", "pad", "box"):
        g = [r for r in scripted if r["goal"] == goal]
        ok = sum(int(r["success"]) for r in g)
        w(f"| {goal} | {ok}/{len(g)} |")
    w("")

    w("## E2 world-model data efficiency")
    w("")
    w("Source: `results/e2.csv`. Three recipes, N robot episodes, three seeds.")
    w("The metric is the 10-step block-position error, in centimetres, on")
    w("held-out robot episodes (seeds 900–999), on the 10-step window where the")
    w("block travels farthest. The baseline is `sim_only` at N = 0, which is")
    w('the error of predicting that the block never moves. Lower is better.')
    w("Each cell is the mean ± the standard deviation of the three seeds.")
    w("")
    grouped: dict[tuple[str, int], list[float]] = defaultdict(list)
    auroc: dict[tuple[str, int], list[float]] = defaultdict(list)
    for row in e2:
        key = (row["variant"], int(float(row["N"])))
        grouped[key].append(float(row["pos_err_cm"]))
        auroc[key].append(float(row["attach_auroc"]))
    baseline = float(np.mean(grouped[("sim_only", 0)]))
    ns = sorted({int(float(r["N"])) for r in e2})
    variants = ("sim_only", "pretrain_ft", "cotrain")
    labels = {
        "sim_only": "Robot data only",
        "pretrain_ft": "Phone clips, then robot data",
        "cotrain": "Both from the start",
    }
    w("| N | " + " | ".join(labels[v] for v in variants) + " |")
    w("|---:|" + "|".join(["---:" for _ in variants]) + "|")
    for n in ns:
        cells = [_mean_std(grouped[(v, n)]) for v in variants]
        w(f"| {n} | " + " | ".join(cells) + " |")
    w("")
    w(f'Baseline, "the lid never moves": {baseline:.2f} cm (`sim_only`, N = 0).')
    w("Claim: pretraining on the phone clips lowers this error, and does so")
    w("with fewer robot episodes than training from the robot alone. The table")
    w("does not support that claim. No cell is below the baseline.")
    w("")
    w("![10-step error against the number of robot episodes](results/e2_curve.png)")
    w("")

    w("## Attach AUROC")
    w("")
    w("Source: `results/e2.csv`, column `attach_auroc`, same windows as E2.")
    w("0.5 is a coin toss. 1.0 is perfect. The question is whether the lid is")
    w("in the hand on that step. The baseline is 0.5.")
    w("")
    w("| N | " + " | ".join(labels[v] for v in variants) + " |")
    w("|---:|" + "|".join(["---:" for _ in variants]) + "|")
    for n in (0, 25, 300):
        if n not in ns:
            continue
        cells = [_mean_std(auroc[(v, n)]) for v in variants]
        w(f"| {n} | " + " | ".join(cells) + " |")
    w("")
    w("Claim: the model learns whether the lid is in the hand, and robot")
    w("episodes make that answer sharper. The metric is AUROC. The evidence is")
    w("the rise from N = 0 to N = 25 in every recipe. Seeds are the three")
    w("values whose mean is in the cell.")
    w("")

    w("## Failure-clip ablation")
    w("")
    w("E6 in `docs/EXPLAINER.md` would train once with the failure clips and")
    w("once without them. That run was not done. There is no separate results")
    w("file for it. What the QC file does show is which failure clips were")
    w("usable at all:")
    w("")
    w("| Type | What it is | Passed |")
    w("|---|---|---:|")
    names = {
        "F1": "pinch closes beside the lid",
        "F2": "lid is dropped in the air",
        "F3": "lid is set down short of the plate",
        "F4": "open hand pushes the lid",
    }
    for kind in ("F1", "F2", "F3", "F4"):
        rows = by_type.get(kind, [])
        w(f"| {kind} | {names[kind]} | {n_pass(rows)}/{len(rows)} |")
    w("")
    w("Source: `results/extraction_report.csv`. The misses and the pushes fail")
    w("the grasp-count rule, so they never enter the retargeting set. The world")
    w("model's training file still contains every extracted clip, including")
    w("those that failed QC. That is not the ablation E6 asked for.")
    w("")

    w("## Embodiment-gap heatmap")
    w("")
    w("Source: `results/gap_heatmap.png`, from `scripts/fig_gap_heatmap.py`.")
    w("Each panel is the fraction of ensemble members that predict a lift past")
    w("the 1 cm height tolerance, for a grasp shifted by up to 3 cm. The right")
    w("panel is the simulator actually running the arm. No numeric table was")
    w("saved beside the figure, so this section does not quote cell values.")
    w("")
    w("![Lift probability against grasp offset](results/gap_heatmap.png)")
    w("")
    w("Claim the figure was built to test: the human-only model should show a")
    w("wider high region than the simulator, and adaptation should narrow it.")
    w("Read the figure. The two learned panels are low across the grid. The")
    w("simulator lifts in a patch around the lid. The evidence does not support")
    w("the wider-human-region claim.")
    w("")

    w("## Held-out clip overlay")
    w("")
    w("Source: `results/human_overlay_clip008.mp4`. The phone-only model is")
    w("rolled forward on held-out clip 8 using the measured hand motion. Blue")
    w("is the measured lid. Orange is the prediction. A frame-by-frame error")
    w("was not written to a csv, so this section does not quote a centimetre")
    w("error.")
    w("")

    w("## MPC / E3")
    w("")
    w("Not run. `src/palm_prior/plan/mpc.py` and `src/palm_prior/plan/cem.py`")
    w("exist, and `tests/test_cem.py` checks the optimiser on a quadratic.")
    w("There is no `results/` file for a closed-loop episode. E3 was skipped")
    w("because E2 did not beat the never-moves baseline, and a planner cannot")
    w("repair a predictor that is worse than leaving the lid still.")
    w("")

    w("## What worked / what didn't")
    w("")
    naive_ok, naive_n, naive_med = e1_claims["naive"]
    two_ok, two_n, two_med = e1_claims["two_anchor"]
    w("**Worked.** The lid is tracked. Two-anchor retargeting places the lid")
    w(f"on {two_ok}/{two_n} layouts (median miss {two_med:.1f} cm). The fixed")
    w(f"map places it on {naive_ok}/{naive_n} (median miss {naive_med:.1f} cm).")
    w("The scripted pick, which is told the positions, succeeds on the counts")
    w("in the table above. The attach head's AUROC rises once robot episodes")
    w("are added.")
    w("")
    w("**Did not work.** Phone-clip pretraining does not beat")
    w(f"{baseline:.2f} cm. At the largest N, the phone-clip recipe is the")
    w("highest error of the three. The misses and the pushes do not pass QC.")
    w("The heatmap does not show a human model that knows a near-miss fails.")
    w("MPC was not run.")
    w("")

    w("## Why this is useful")
    w("")
    w("A robot team that only records successes learns a path and not a")
    w("consequence. A clip where the pinch misses, or the lid is dropped, is a")
    w("labelled example of the lid staying put or falling. The shared state")
    w("makes that example usable on a different arm, because it stores the")
    w("hand relative to the lid and the lid relative to the target, not a")
    w("picture of a particular body. On this dataset the position predictor")
    w("did not cash that out. The retargeting did: the same clips, read as a")
    w("path pinned at the grasp and at the release, beat a map that ignores")
    w("where the objects are. The useful piece a team can take is that")
    w("measurement, plus the attach bit, which does learn. The position model")
    w("needs a finger estimate that stays on the fingers, which the red dot")
    w("in the extraction previews does not.")
    w("")

    root = Path(__file__).resolve().parents[1]
    dest = root / "results" / "v1" / "summary_from_csv.md"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {dest}")
    print(f"QC {n_ok}/{n_clips}  E1 two-anchor {two_ok}/{two_n}  naive {naive_ok}/{naive_n}")
    print(f"never-moves {baseline:.2f} cm")


if __name__ == "__main__":
    with Timer("summarise_results"):
        main(sys.argv[1:])
